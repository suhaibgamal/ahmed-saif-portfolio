function getBreadcrumbItems(locale, page, work) {
  const t = content[locale];
  const homeLabel = t.nav.find((item) => item.page === "home")?.label || t.brandName;
  const currentLabel = t.nav.find((item) => item.page === page)?.label || t.brandName;
  const items = [
    {
      "@type": "ListItem",
      position: 1,
      name: homeLabel,
      item: getAbsoluteUrl(pageRoutes[locale].home)
    }
  ];

  if (page !== "home") {
    items.push({
      "@type": "ListItem",
      position: 2,
      name: currentLabel,
      item: getAbsoluteUrl(pageRoutes[locale][page])
    });
  }

  if (work) {
    const copy = getWorkCopy(work, locale);
    items.push({
      "@type": "ListItem",
      position: 3,
      name: copy.title,
      item: getAbsoluteUrl(getWorkPath(locale, work))
    });
  }

  return items;
}

function getMusicCatalogData(locale) {
  const t = content[locale];
  const catalogUrl = getAbsoluteUrl(pageRoutes[locale].works);
  const artistId = `${siteUrl}/#artist`;

  return {
    "@type": "MusicPlaylist",
    "@id": `${catalogUrl}#catalog`,
    name: t.meta.works.title,
    description: t.meta.works.description,
    url: catalogUrl,
    numTracks: works.length,
    creator: { "@id": artistId },
    track: works.map((work, index) => {
      const copy = getWorkCopy(work, locale);

      return {
        "@type": "MusicRecording",
        position: index + 1,
        name: copy.title,
        alternateName: copy.subtitle,
        byArtist: { "@id": artistId },
        datePublished: work.uploadDate,
        duration: getIsoDuration(work.durationSeconds),
        genre: copy.mood,
        description: copy.note,
        url: getAbsoluteUrl(getWorkPath(locale, work)),
        sameAs: getYoutubeWatchUrl(work),
        subjectOf: { "@id": `${getAbsoluteUrl(getWorkPath(locale, work))}#video` }
      };
    })
  };
}

